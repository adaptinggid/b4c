/**
 * Retrieve a GameLevel by its numeric ID.
 */
export function getLevelById(id: number): GameLevel | undefined {
  return GAME_LEVELS.find((lvl) => lvl.id === id);
}

/**
 * Retrieve a GameLevel by its URL slug.
 */
export function getLevelBySlug(slug: string): GameLevel | undefined {
  return GAME_LEVELS.find((lvl) => lvl.slug === slug);
}
