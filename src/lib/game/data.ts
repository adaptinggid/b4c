// ─── Helpers ──────────────────────────────────────────────────────────────────

export function getTierBySlug(slug: string): GameTier | undefined {
  return GAME_TIERS.find((t) => t.slug === slug);
}

export function getTierByDifficulty(difficulty: string): GameTier | undefined {
  return GAME_TIERS.find((t) => t.difficulty === difficulty);
}

export function getSetById(setId: string): { tier: GameTier; set: GameSet } | undefined {
  for (const tier of GAME_TIERS) {
    const set = tier.sets.find((s) => s.id === setId);
    if (set) return { tier, set };
  }
  return undefined;
}

/**
 * Build a GameLevel-compatible object from a GameSet + GameTier
 * (for backward compatibility with the generator and validator).
 */
export function setToLevel(tier: GameTier, set: GameSet) {
  return {
    id: parseInt(set.id.replace(/\D/g, ''), 10) || 0,
    slug: set.id,
    title: set.title,
    description: set.description,
    difficulty: tier.difficulty,
    gridSize: set.gridSize,
    words: set.words,
    learningObjective: set.learningObjective,
    allowedDirections: tier.allowedDirections,
    maxHints: set.maxHints,
    estimatedMinutes: set.estimatedMinutes,
  };
}

// ─── Legacy shim (keep old imports working) ───────────────────────────────────

/**
 * Flat array of all sets across all tiers, ordered Beginner → Intermediate → Advanced.
 * Each entry is augmented with tier metadata for backward-compatibility.
 */
export const GAME_LEVELS = GAME_TIERS.flatMap((tier) =>
  tier.sets.map((set, idx) =>
    Object.assign(setToLevel(tier, set), {
      id: idx + 1,
      slug: set.id,
    })
  )
);

export function getLevelById(id: number) {
  return GAME_LEVELS.find((l) => l.id === id);
}

export function getLevelBySlug(slug: string) {
  return GAME_LEVELS.find((l) => l.slug === slug);
}
